// Byte-identity round-trip + generator tests for src/zcfEncoder.ts.
//
// Asserts that parse(file) -> encode(parsed) reproduces the input bytes
// exactly for three real .zcf files. If this passes, the TS port has
// the same byte-level behaviour as the Python reference encoder.
//
// Also verifies that generateZcf(spec, template):
//   - produces a file that re-parses cleanly,
//   - whose config_name + module + circuit list match the spec,
//   - and that does NOT match the template byte-for-byte (i.e. mutation
//     actually happened).

import fs from 'node:fs'
import path from 'node:path'
import {
  parseZcfFull,
  encodeZcf,
  generateZcf,
  crc8,
  crc32Lo20,
  SUB_CATEGORY_BIT
} from '../dist/zcfEncoder.js'
import { parseZcf as heuristicParseZcf } from '../dist/zcfParser.js'

const here = path.dirname(new URL(import.meta.url).pathname)
const fixturesDir = path.join(here, 'fixtures')

function assertEqualBytes (actual, expected, label) {
  if (actual.length !== expected.length) {
    throw new Error(`${label}: length mismatch ${actual.length} vs ${expected.length}`)
  }
  for (let i = 0; i < actual.length; i++) {
    if (actual[i] !== expected[i]) {
      const ctx = (off) => Array.from(actual.slice(Math.max(0, off - 4), off + 4)).map(b => b.toString(16).padStart(2, '0')).join(' ')
      throw new Error(`${label}: byte ${i} differs (got 0x${actual[i].toString(16)}, want 0x${expected[i].toString(16)}); context actual=[${ctx(i)}] expected=[${Array.from(expected.slice(Math.max(0, i - 4), i + 4)).map(b => b.toString(16).padStart(2, '0')).join(' ')}]`)
    }
  }
}

// CompassRose.zcf (6384 bytes) is the largest real .zcf we round-trip
// against. It is a customer config, so it isn't bundled with the plugin;
// drop a copy into test/fixtures/ to include it in the round-trip set.
const samples = ['Test.zcf', 'config-6.zcf', 'CompassRose.zcf']

for (const name of samples) {
  const filePath = path.join(fixturesDir, name)
  if (!fs.existsSync(filePath)) {
    console.log(`round-trip ${name}: SKIPPED (fixture not present)`)
    continue
  }
  const data = fs.readFileSync(filePath)
  const parsed = parseZcfFull(data)
  const out = encodeZcf(parsed)
  assertEqualBytes(out, data, `round-trip ${name}`)
  console.log(`round-trip ${name} (${data.length} bytes): OK`)
}

// CRC sanity: matches the Python reference (zcf_header.crc8 / crc32_lo20)
// for the same input.
const known = Buffer.from('Hello, world!', 'ascii')
const c8 = crc8(known)
if (c8 !== 0xbc) throw new Error(`crc8('Hello, world!') = 0x${c8.toString(16)}, want 0xbc`)
const c32 = crc32Lo20(known)
if (c32 !== 0x6c6e6) {
  throw new Error(`crc32Lo20('Hello, world!') = 0x${c32.toString(16)}, want 0x6c6e6`)
}
console.log('CRC sanity: OK')

// Generator: synthesise from Test.zcf as template.
const template = fs.readFileSync(path.join(here, '..', 'templates', 'template.zcf'))
const spec = {
  configName: 'SignalK Bank 0',
  module: { dipswitch: 0x18, name: 'SignalK Switch Bank' },
  circuits: [
    { name: 'Anchor Light', circuitId: 13 },
    { name: 'Cabin Light', circuitId: 14 },
    { name: 'Spreader Light', circuitId: 15 }
  ]
}
const generated = generateZcf(spec, template)

if (generated.equals(template)) throw new Error('generated bytes equal template — mutation did not happen')

const reparsed = parseZcfFull(generated)
if (reparsed.body.configName.name !== spec.configName) {
  throw new Error(`generated config_name = ${reparsed.body.configName.name}, want ${spec.configName}`)
}
// 2 modules expected: our emulated Output Interface + the template's
// Display Interface (m1=0x10) which we now preserve so the
// Configuration Tool's "Display Interface" tree node is populated and
// the per-circuit "All Display Interfaces" Circuit Control binds.
if (reparsed.body.modules.records.length !== 2) {
  throw new Error(`generated has ${reparsed.body.modules.records.length} modules, want 2`)
}
const m = reparsed.body.modules.records[0]
if (m.dipswitch !== spec.module.dipswitch) throw new Error(`module dipswitch = 0x${m.dipswitch.toString(16)}, want 0x${spec.module.dipswitch.toString(16)}`)
if (m.name !== spec.module.name) throw new Error(`module name = ${m.name}, want ${spec.module.name}`)
// Generator pads to the module type's output count -- m1=0x0f is 6
// outputs, so a 3-circuit spec generates 6 circuits (3 user + 3 padded
// "Spare DC" entries to suppress the "Paralleled with DC1" placeholders
// the Configuration Tool synthesises for unused outputs).
if (reparsed.body.circuits.records.length < spec.circuits.length) {
  throw new Error(`generated has ${reparsed.body.circuits.records.length} circuits, want >= ${spec.circuits.length}`)
}
for (let i = 0; i < spec.circuits.length; i++) {
  if (reparsed.body.circuits.records[i].name !== spec.circuits[i].name) {
    throw new Error(`circuit ${i} name = ${reparsed.body.circuits.records[i].name}, want ${spec.circuits[i].name}`)
  }
  if (reparsed.body.circuitIds.records[i].circuitId !== spec.circuits[i].circuitId) {
    throw new Error(`circuit ${i} id = ${reparsed.body.circuitIds.records[i].circuitId}, want ${spec.circuits[i].circuitId}`)
  }
  if (reparsed.body.circuitIds.records[i].name !== spec.circuits[i].name) {
    throw new Error(`circuit_id ${i} name = ${reparsed.body.circuitIds.records[i].name}, want ${spec.circuits[i].name}`)
  }
}

// Verify the generated file's CRCs by re-encoding the re-parsed structure.
const reencoded = encodeZcf(reparsed)
assertEqualBytes(reencoded, generated, 'generated re-round-trip')
console.log(`generator: produced ${generated.length}-byte .zcf with ${spec.circuits.length} circuits, re-parses cleanly, re-encodes byte-identical`)

// Critical regression: every output.channelAddress and every
// displayRef.displayAddress (and circuit_id.channelAddress) must be
// dipswitch-namespaced (high byte == module dipswitch). If this drifts,
// the CZone Configuration Tool crashes in GetChannelString.
const dip = spec.module.dipswitch & 0xff
for (const ckt of reparsed.body.circuits.records) {
  for (const o of ckt.outputs) {
    // channel_address == 0x0000 is the "All Display Interfaces" wildcard
    // Circuit Control entry; it is not dipswitch-namespaced (its dip
    // byte is intentionally 0).
    if (o.channelAddress === 0) continue
    if (((o.channelAddress >> 8) & 0xff) !== dip) {
      throw new Error(`output.channelAddress 0x${o.channelAddress.toString(16)} not under dipswitch 0x${dip.toString(16)}`)
    }
  }
  for (const d of ckt.displayRefs) {
    if (((d.displayAddress >> 8) & 0xff) !== dip) {
      throw new Error(`dref.displayAddress 0x${d.displayAddress.toString(16)} not under dipswitch 0x${dip.toString(16)}`)
    }
  }
}
for (const cid of reparsed.body.circuitIds.records) {
  if (((cid.channelAddress >> 8) & 0xff) !== dip) {
    throw new Error(`circuit_id.channelAddress 0x${cid.channelAddress.toString(16)} not under dipswitch 0x${dip.toString(16)}`)
  }
}
console.log(`channel-address dipswitch namespacing (high byte == 0x${dip.toString(16)}): OK`)

// Heuristic parser sanity: drive the generated bytes through the SAME
// scanner the runtime uses on inbound PGN 130816 reassembly. The parser
// scans for length-prefixed strings appearing >= 2x; some labels (the
// module name, the labelled-entity name) can show up twice for unrelated
// reasons and inflate the count, so we only assert that every spec
// circuit is present, not that the count matches exactly.
const heuristic = heuristicParseZcf(generated)
const heurNames = new Set(heuristic.circuits.map(c => c.name))
for (const c of spec.circuits) {
  if (!heurNames.has(c.name)) {
    throw new Error(`heuristic parser missing circuit name ${JSON.stringify(c.name)}; saw ${JSON.stringify([...heurNames])}`)
  }
}
const heurIdsForSpec = spec.circuits.map(c => {
  const found = heuristic.circuits.find(h => h.name === c.name)
  return found ? found.circuitId : -1
})
for (let i = 0; i < spec.circuits.length; i++) {
  if (heurIdsForSpec[i] !== spec.circuits[i].circuitId) {
    throw new Error(`heuristic parser id for ${spec.circuits[i].name} = ${heurIdsForSpec[i]}, want ${spec.circuits[i].circuitId}`)
  }
}
console.log(`heuristic parser sees all ${spec.circuits.length} spec circuits with correct ids (total parsed: ${heuristic.circuits.length}): OK`)

// Larger spec -- 8 switches, names with characters that exercise the
// length-prefix scanner (numbers, spaces).
const bigSpec = {
  configName: 'My Boat Configuration',
  module: { dipswitch: 0x18, name: 'Helm Switch Bank' },
  circuits: [
    { name: 'Anchor Light', circuitId: 13 },
    { name: 'Cabin Light 1', circuitId: 14 },
    { name: 'Cabin Light 2', circuitId: 15 },
    { name: 'Spreader Light', circuitId: 16 },
    { name: 'Salon Lights', circuitId: 17 },
    { name: 'Galley Lights', circuitId: 18 },
    { name: 'Bilge Pump', circuitId: 19 },
    { name: 'Nav Lights', circuitId: 20 }
  ]
}
const bigGen = generateZcf(bigSpec, template)
const bigParsed = parseZcfFull(bigGen)  // re-parses cleanly
if (bigParsed.body.circuits.records.length !== bigSpec.circuits.length) {
  throw new Error(`big spec: parsed ${bigParsed.body.circuits.records.length} circuits, want ${bigSpec.circuits.length}`)
}
const bigHeuristic = heuristicParseZcf(bigGen)
const bigHeurNames = new Set(bigHeuristic.circuits.map(c => c.name))
for (const c of bigSpec.circuits) {
  if (!bigHeurNames.has(c.name)) {
    throw new Error(`big spec heuristic missing ${JSON.stringify(c.name)}`)
  }
}
console.log(`generator: 8-circuit spec generated ${bigGen.length} bytes, both parsers see all 8 spec circuits`)

// Sub-category: a per-circuit subCategory value lands in the
// circuits-section flags_b verbatim. Verify each spec circuit's
// flags_b matches the supplied subCategory.
const catSpec = {
  configName: 'Cat Test',
  module: { dipswitch: 0x18, name: 'Cat Module' },
  circuits: [
    { name: 'Anchor Light', circuitId: 13, subCategory: SUB_CATEGORY_BIT.NAVIGATION },
    { name: 'Cabin Lights', circuitId: 14, subCategory: SUB_CATEGORY_BIT.LIGHTING },
    { name: 'Bilge Pump',   circuitId: 15, subCategory: SUB_CATEGORY_BIT.PUMPS },
    { name: 'Fridge',       circuitId: 16, subCategory: SUB_CATEGORY_BIT.REFRIGERATION },
    { name: 'VHF',          circuitId: 17, subCategory: SUB_CATEGORY_BIT.COMMUNICATIONS },
    { name: 'LPG',          circuitId: 18, subCategory: SUB_CATEGORY_BIT.HOUSE_HABITAT },
    // No subCategory -> template's flags_b is preserved
    { name: 'Other',        circuitId: 19 }
  ]
}
const catGen = generateZcf(catSpec, template)
const catParsed = parseZcfFull(catGen)
const expectedFlagsB = [
  SUB_CATEGORY_BIT.NAVIGATION,
  SUB_CATEGORY_BIT.LIGHTING,
  SUB_CATEGORY_BIT.PUMPS,
  SUB_CATEGORY_BIT.REFRIGERATION,
  SUB_CATEGORY_BIT.COMMUNICATIONS,
  SUB_CATEGORY_BIT.HOUSE_HABITAT,
  null  // template's flags_b -- Test.zcf is 0x0002 for first circuit
]
for (let i = 0; i < catSpec.circuits.length; i++) {
  const got = catParsed.body.circuits.records[i].flagsB
  const want = expectedFlagsB[i]
  if (want === null) continue  // template-preserved; don't pin a value
  if (got !== want) {
    throw new Error(`circuit ${i} (${catSpec.circuits[i].name}) flags_b = 0x${got.toString(16)}, want 0x${want.toString(16)}`)
  }
}
console.log(`generator: per-circuit subCategory threaded into flags_b correctly: OK`)

// Bank instance: spec.bankInstance lands in labelled_entities[0].field_b.
// Verified against config-6.zcf (field_b=5 + name "SW Bank 5"). Without
// this rewrite the Configuration Tool's Switch Bank PGN config row shows
// Switch Bank Instance = 0 regardless of the user's bank.instance.
const bankSpec = {
  configName: 'Bank 16 Test',
  module: { dipswitch: 0x08, name: 'Bank 16 Module' },
  bankInstance: 16,
  circuits: [{ name: 'Switch 1', circuitId: 13 }]
}
const bankGen = generateZcf(bankSpec, template)
const bankParsed = parseZcfFull(bankGen)
const labelEntsTrailing = bankParsed.body.trailingSections[21]
if (!labelEntsTrailing || labelEntsTrailing.payload.length < 5) {
  throw new Error('labelled_entities trailing section missing or too short')
}
const fieldB = labelEntsTrailing.payload[2]
if (fieldB !== 16) {
  throw new Error(`labelled_entities[0].field_b = ${fieldB}, want 16 (the bank instance)`)
}
console.log(`generator: bankInstance landed in labelled_entities[0].field_b: OK`)

// Paralleled-output suppression: with module type m1=0x0f (3 outputs),
// supplying 1 spec circuit pads to 3 generated circuits so the
// Configuration Tool doesn't show "DC{n} - Paralleled with DC1" rows.
// (Test.zcf's module is m1=0x0f, our generated test files inherit it.)
if (bankParsed.body.circuits.records.length !== 6) {
  throw new Error(`expected 6 circuits after padding (m1=0x0f -> 6 outputs), got ${bankParsed.body.circuits.records.length}`)
}
const paddingNames = bankParsed.body.circuits.records.slice(1).map(c => c.name)
if (paddingNames[0] !== 'Spare DC2' || paddingNames[4] !== 'Spare DC6') {
  throw new Error(`unexpected padding names: ${JSON.stringify(paddingNames)}`)
}
console.log(`generator: padded 1 spec circuit -> 6 generated circuits to match m1=0x0f output count: OK`)

// Display Interface + wildcard output: every generated circuit must
// have a leading outputs[0] with channelAddress = 0x0000 (the "All
// Display Interfaces" wildcard the Configuration Tool's Circuit
// Control surface keys off), AND the modules list must include both
// our Output Interface (m1=0x0f) and the template's Display Interface
// (m1=0x10) -- otherwise mister nui's side-bar binding doesn't work.
const sidebarSpec = {
  configName: 'Sidebar Test',
  module: { dipswitch: 0x18, name: 'Sidebar Module' },
  bankInstance: 0,
  circuits: [{ name: 'Lights', circuitId: 13 }]
}
const sidebarGen = generateZcf(sidebarSpec, template)
const sidebarParsed = parseZcfFull(sidebarGen)
if (sidebarParsed.body.modules.records.length < 2) {
  throw new Error(`sidebar config: expected >=2 modules (Output + Display Interface), got ${sidebarParsed.body.modules.records.length}`)
}
const hasDisplayInterface = sidebarParsed.body.modules.records.some(m => m.moduleSpecificValue === 0x10)
if (!hasDisplayInterface) {
  throw new Error(`sidebar config: no Display Interface module (m1=0x10) in generated file -- "All Display Interfaces" Circuit Control will be missing`)
}
for (const ckt of sidebarParsed.body.circuits.records) {
  if (ckt.outputs.length < 2 || ckt.outputs[0].channelAddress !== 0) {
    throw new Error(`circuit ${ckt.name} missing leading outputs[0] chan=0x0000 wildcard (got outputs=${ckt.outputs.map(o => '0x' + o.channelAddress.toString(16)).join(',')})`)
  }
}
console.log(`generator: every circuit has leading wildcard output + Display Interface module preserved: OK`)

// Module type override: spec.module.typeCode rewrites the module's
// module_specific_value byte. C6 hardware uses m1=0x09 (the
// Configuration Tool labels its outputs C1..C6). Verify the override
// lands in the encoded file.
const c6Spec = {
  configName: 'C6 Test',
  module: { dipswitch: 0x18, name: 'C6 Module', typeCode: 0x09 },
  bankInstance: 0,
  circuits: [{ name: 'C1 Load', circuitId: 13 }]
}
const c6Gen = generateZcf(c6Spec, template)
const c6Parsed = parseZcfFull(c6Gen)
if (c6Parsed.body.modules.records[0].moduleSpecificValue !== 0x09) {
  throw new Error(`m1 typeCode override failed: got 0x${c6Parsed.body.modules.records[0].moduleSpecificValue.toString(16)}, want 0x09`)
}
console.log(`generator: typeCode override 0x09 (C6/COI) lands in module_specific_value: OK`)

console.log('\nzcf-encoder test: PASS')
